#!/usr/bin/env node
// Builds the static Firebase Hosting bundle into dist/ so Harrington can be
// deployed 100% on Firebase (Hosting + Auth + Firestore + Storage + Gemini AI).
import { copyFile, cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitTeachingResearch, RESEARCH_FILE } from '../lib/teaching-research.mjs';
import { CURRICULUM_ID, trimStandards } from '../src/js/curriculum.js';
import { MAX_FIGURE_BYTES, figureIdOf, figureMeta, figureProblems } from '../src/js/figures/contract.js';
import { CACHE_DIR, ensureTaxonomyCache } from '../tests/e2e/support/taxonomy.mjs';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const STATIC_TAXONOMY_FILES = ['topics.json', 'dependencies.json', 'clusters.json', 'manifest.json'];

async function collectFigures(figuresDir) {
  const names = await readdir(figuresDir).catch(() => []);
  const figures = [];
  for (const name of names.sort()) {
    const id = figureIdOf(name);
    if (!id) continue;
    const path = join(figuresDir, name);
    const details = await stat(path).catch(() => null);
    if (!details?.isFile() || details.size > MAX_FIGURE_BYTES) continue;
    const html = await readFile(path, 'utf8');
    if (figureProblems(name, html).length) continue;
    figures.push({ id, ...figureMeta(html) });
  }
  return figures;
}

const DEFAULT_ALLOWED_EMAIL_HASHES = [
  '3630ac935b7662b92f7637f6ca90495fd5fe6d1fb563ae61e4a143d7c4b43edf',
];

async function resolveFirebaseWebappConfig(rootDir, env = process.env) {
  const rawEnv = String(env.HARRINGTON_FIREBASE_CONFIG || '').trim();
  if (rawEnv) {
    const parsed = JSON.parse(rawEnv);
    const { allowedEmails: _drop, ...safe } = parsed;
    return { allowedEmailHashes: DEFAULT_ALLOWED_EMAIL_HASHES, ...safe };
  }
  try {
    const rawFile = await readFile(join(rootDir, '.firebase-webapp.json'), 'utf8');
    const parsed = JSON.parse(rawFile);
    const { allowedEmails: _drop, ...safe } = parsed;
    return { allowedEmailHashes: DEFAULT_ALLOWED_EMAIL_HASHES, ...safe };
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

export async function buildFirebase({
  rootDir = repoRoot,
  distDir = resolve(rootDir, 'dist'),
  cacheDir = CACHE_DIR,
  log = console.log,
  env = process.env,
} = {}) {
  await ensureTaxonomyCache({ log });

  await rm(distDir, { recursive: true, force: true });
  await mkdir(distDir, { recursive: true });

  const srcDir = join(rootDir, 'src');
  await cp(srcDir, distDir, {
    recursive: true,
    filter: (source) => !source.endsWith('/.DS_Store') && !source.endsWith('\\.DS_Store'),
  });

  const apiDir = join(distDir, 'api');
  const taxonomyOut = join(apiDir, 'taxonomy');
  const standardsOut = join(taxonomyOut, 'standards');
  await mkdir(standardsOut, { recursive: true });

  for (const name of STATIC_TAXONOMY_FILES) {
    await copyFile(join(cacheDir, name), join(taxonomyOut, name));
  }

  const standardsRaw = JSON.parse(await readFile(join(cacheDir, 'curriculum-standards.json'), 'utf8'));
  const trimmed = trimStandards(standardsRaw, CURRICULUM_ID);
  await writeFile(join(standardsOut, `${CURRICULUM_ID}.json`), JSON.stringify(trimmed));

  const researchSource = await readFile(join(cacheDir, RESEARCH_FILE));
  const researchIndex = await splitTeachingResearch(researchSource, taxonomyOut);
  await rm(join(taxonomyOut, 'research', 'index.json'), { force: true });
  await writeFile(
    join(taxonomyOut, 'research.json'),
    JSON.stringify({ topicIds: researchIndex.topicIds, caveat: researchIndex.caveat }),
  );

  const figures = await collectFigures(join(srcDir, 'figures'));
  await writeFile(join(apiDir, 'figures.json'), JSON.stringify({ figures }));

  const webappConfig = await resolveFirebaseWebappConfig(rootDir, env);
  if (webappConfig) {
    const configSource = [
      '// Generated by scripts/build-firebase.mjs for Firebase Hosting.',
      `export const FIREBASE_CONFIG = ${JSON.stringify(webappConfig, null, 2)};`,
      '',
      'export function activeFirebaseConfig(override = null) {',
      '  return override || globalThis.__HARRINGTON_FIREBASE_CONFIG__ || FIREBASE_CONFIG || null;',
      '}',
      '',
    ].join('\n');
    await writeFile(join(distDir, 'js', 'firebase-config.js'), configSource);
  }

  return {
    distDir,
    figureCount: figures.length,
    researchCount: researchIndex.topicIds.length,
    configured: Boolean(webappConfig),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = await buildFirebase();
  console.log(`Built Firebase Hosting bundle in ${result.distDir} (${result.figureCount} figures, ${result.researchCount} teaching guides, config=${result.configured}).`);
}
